'use strict';

const { Pool, types } = require('pg');

// pg returns BIGINT as a string by default; seq is a number here.
types.setTypeParser(20, (value) => Number(value));

// Serialize writes so status checks and max(seq)+1 stay consistent.
const ADVISORY_LOCK_KEY = 0x48454c50; // "HELP"

function convert(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

class Db {
  constructor(pool) {
    this.pool = pool;
  }

  async query(sql, params = []) {
    return this.pool.query(convert(sql), params);
  }

  async all(sql, params = []) {
    const result = await this.query(sql, params);
    return result.rows;
  }

  async one(sql, params = []) {
    const result = await this.query(sql, params);
    return result.rows[0];
  }

  async run(sql, params = []) {
    const result = await this.query(sql, params);
    return result.rowCount;
  }
}

class Tx {
  constructor(client) {
    this.client = client;
  }

  async query(sql, params = []) {
    return this.client.query(convert(sql), params);
  }

  async all(sql, params = []) {
    const result = await this.query(sql, params);
    return result.rows;
  }

  async one(sql, params = []) {
    const result = await this.query(sql, params);
    return result.rows[0];
  }

  async run(sql, params = []) {
    const result = await this.query(sql, params);
    return result.rowCount;
  }
}

function createDb(config) {
  const poolConfig = { connectionString: config.databaseUrl };
  if (config.dbSchema) {
    // Pin the schema for every pooled connection.
    poolConfig.options = `-c search_path=${config.dbSchema}`;
  }
  return new Db(new Pool(poolConfig));
}

async function withTransaction(db, fn) {
  const client = await db.pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock($1)', [ADVISORY_LOCK_KEY]);
    const result = await fn(new Tx(client));
    await client.query('COMMIT');
    return result;
  } catch (error) {
    try {
      await client.query('ROLLBACK');
    } catch {
      // The transaction may already be aborted.
    }
    throw error;
  } finally {
    client.release();
  }
}

async function closeDb(db) {
  await db.pool.end();
}

